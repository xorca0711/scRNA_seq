#!/usr/bin/env python
"""Generate NEGATIVE_RESULTS.md from the claims register.

This repository's rule is that refuted and negative results stay visible and
that reports are generated from logged artefacts rather than typed from memory.
Until now the negative results were spread across `CLAIMS.md`, the per-paper
trial plans and `FINDINGS.md`, so nobody could see them in one place, and a
hand-written summary of them would drift from the register within a session.

This script reads `CLAIMS.md`, selects the rows whose status is refuted, not
established, or retracted, and writes `NEGATIVE_RESULTS.md`. It computes
nothing scientific: every number and every sentence comes from a register row,
so the generated page cannot disagree with the register.

Artefact paths are emitted as inline code rather than as links, because the
register writes some of them relative to a paper folder and some relative to
the repository root, and a generated page with broken links is worse than one
that asks the reader to open the register.

Run: python analysis/scripts/14_write_negative_results.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "CLAIMS.md"
TARGET = REPO / "NEGATIVE_RESULTS.md"

ROW = re.compile(r"^\|\s*(C\d+)\s*\|")
STAGE = re.compile(r"^##\s+(.*)$")

# Which register statuses belong on this page, and the heading each lands under.
# Matched against the lowercased status cell, first match wins, so the more
# specific phrases come first.
BUCKETS = [
    ("retracted", "Retracted or superseded, kept on display"),
    ("refuted", "Refuted"),
    ("not establishable", "Not establishable with the data that exists"),
    ("not established", "Not established"),
]


def cells(line: str) -> list[str]:
    parts = [c.strip() for c in line.split("|")]
    return parts[1:-1] if parts and parts[0] == "" else parts


def bucket_of(status: str) -> str | None:
    low = status.lower()
    for key, heading in BUCKETS:
        if key in low:
            return heading
    return None


def collect(text: str) -> list[dict]:
    stage = "Unassigned"
    out = []
    for line in text.splitlines():
        header = STAGE.match(line)
        if header:
            stage = header.group(1).strip()
            continue
        if not ROW.match(line):
            continue
        field = cells(line)
        if len(field) < 6:
            continue
        identifier, claim, basis, artefact, status = field[0], field[1], field[2], field[3], field[4]
        heading = bucket_of(status)
        if heading is None:
            continue
        out.append({"id": identifier, "claim": claim, "basis": basis, "artefact": artefact,
                    "status": status, "stage": stage, "bucket": heading})
    return out


def plain(cell: str) -> str:
    """Strip Markdown links down to their text, so no generated link can break."""
    cell = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", cell)
    return cell.replace("`", "").strip()


def main() -> None:
    if not SOURCE.exists():
        raise SystemExit(f"{SOURCE} is missing; refusing to write a page with no source")
    rows = collect(SOURCE.read_text(encoding="utf-8"))
    if not rows:
        raise SystemExit("no refuted, not-established or retracted rows found; refusing to write an empty page")

    order = [heading for _, heading in BUCKETS]
    counts = {h: sum(1 for r in rows if r["bucket"] == h) for h in order}

    lines = [
        "# Negative results",
        "",
        "**Generated by `analysis/scripts/14_write_negative_results.py` from",
        "[`CLAIMS.md`](CLAIMS.md). Do not edit this file by hand; edit the register and",
        "re-run the script.**",
        "",
        "Every claim this repository has refuted, could not establish, or has retracted,",
        "in one place. A result is on this page because a logged artefact says so, and",
        "the wording is the register's own. Rows stay here permanently: a refutation is a",
        "result, and several of these refute claims the repository itself had made.",
        "",
        "Artefact paths are inline code rather than links, because the register writes",
        "some of them relative to a paper folder and some relative to the repository",
        "root. Open the register row for the full context and the owner's judgement of",
        "the claim's potential.",
        "",
        "| Bucket | Rows |",
        "|---|--:|",
    ]
    for heading in order:
        lines.append(f"| {heading} | {counts[heading]} |")
    lines += [f"| **Total** | **{len(rows)}** |", ""]
    lines += [
        "Some of these rows refute a claim this repository itself had made, and some",
        "refute a method it had used. No count is given here, because deciding which is",
        "which is a judgement rather than something the register encodes, and a number",
        "this script inferred would be a number nobody checked. Each row's own text says",
        "what was refuted and what settled it.",
        "",
    ]

    for heading in order:
        group = [r for r in rows if r["bucket"] == heading]
        if not group:
            continue
        lines += ["---", "", f"## {heading}", ""]
        for row in sorted(group, key=lambda r: int(r["id"][1:])):
            lines += [
                f"### {row['id']}. {plain(row['claim'])}",
                "",
                f"- **Status in the register:** {plain(row['status'])}",
                f"- **What settled it:** {plain(row['basis'])}",
                f"- **Artefact:** `{plain(row['artefact'])}`",
                f"- **Where it came from:** {plain(row['stage'])}",
                "",
            ]

    lines += [
        "---",
        "",
        "## How to read a row here",
        "",
        "A refuted row was tested and failed. A not-established row was never",
        "demonstrated, which in this repository usually means the deposit could not",
        "carry the test rather than that the biology is absent, and the row says which.",
        "A not-establishable row names a structural limit of the data. A retracted row",
        "was claimed, then withdrawn, and is kept so the withdrawal is visible.",
        "",
        "Nothing on this page should be quoted as evidence that a phenomenon does not",
        "exist. Several rows record a test that could only have detected a large effect,",
        "and they say so.",
        "",
    ]

    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {TARGET.relative_to(REPO)} with {len(rows)} rows")
    for heading in order:
        print(f"  {counts[heading]:3d}  {heading}")


if __name__ == "__main__":
    main()
